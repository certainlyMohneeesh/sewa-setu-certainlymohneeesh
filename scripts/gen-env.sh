#!/bin/sh
# Create a private .env for docker compose with fresh random secrets.
# Never overwrites an existing file. The values are not printed.
#   sh scripts/gen-env.sh
set -eu

ENV_FILE="${ENV_FILE:-.env}"
if [ -e "$ENV_FILE" ]; then
    echo "$ENV_FILE already exists; not overwriting it." >&2
    exit 1
fi

rand() {  # rand <tr character set> <length>
    LC_ALL=C tr -dc "$1" < /dev/urandom | head -c "$2"
}

umask 077
{
    echo "# Generated by scripts/gen-env.sh. Private: never commit or share this file."
    echo "POSTGRES_PASSWORD=$(rand 'A-Za-z0-9' 32)"
    echo "SECRET_KEY=$(rand 'a-f0-9' 64)"
    echo "ADMIN_USERNAME=swd-admin"
    echo "ADMIN_PASSWORD=$(rand 'A-Za-z0-9' 24)"
} > "$ENV_FILE"

echo "Created $ENV_FILE (readable only by you)."
echo "The admin password is the ADMIN_PASSWORD line in that file."
